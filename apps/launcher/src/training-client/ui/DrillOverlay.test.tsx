// @vitest-environment jsdom
import { act, createRef } from "react";
import { createRoot } from "react-dom/client";
import { expect, it, vi } from "vitest";
import { DRILL_CATALOG } from "@flashfront/core";
import { DrillOverlay, type DrillOverlayHandle } from "./DrillOverlay";
import type { ClientBridge } from "../bridge";
import type { DrillReferee, RefereeEvent } from "../DrillReferee";
import type { TrainingBridgeApi } from "../../shared";
it("coach card on wrong, menu leave reports left, and first pass is Great", async () => {
  vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
  const host = document.createElement("div"); document.body.append(host); const root = createRoot(host);
  const overlay = createRef<DrillOverlayHandle>();
  const emit = (event: RefereeEvent) => overlay.current!.onRefereeEvent(event);
  const server = { pause: vi.fn(), resume: vi.fn() };
  const bridge = { game: () => undefined, server: () => server } as unknown as ClientBridge;
  const referee = { keepPlaying: vi.fn(), reset: vi.fn() } as unknown as DrillReferee;
  const api = { report: vi.fn(), close: vi.fn() } as unknown as TrainingBridgeApi;
  const drill = DRILL_CATALOG.find(d => d.check.kind === "send")!;
  await act(async () => root.render(<DrillOverlay ref={overlay} bridge={bridge} referee={referee} api={api} drill={drill} />));
  await act(async () => { window.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true })); });
  await act(async () => { [...host.querySelectorAll("button")].find(b => b.textContent === "Leave")!.click(); });
  expect(api.report).toHaveBeenCalledWith({ kind: "left" });
  await act(async () => emit({ kind: "wrong", evidence: { sentPct: 70, reservePct: 30 }, held: null }));
  expect(host.querySelector("h2")?.textContent).toBe("Keep a reserve");
  expect(host.querySelectorAll(".ff-btn-primary")).toHaveLength(1);
  expect(host.textContent).toContain("Rewind and watch the coach"); expect(host.textContent).toContain("Try again"); expect(host.textContent).toContain("Keep playing");
  await act(async () => { [...host.querySelectorAll("button")].find(b => b.textContent === "Try again")!.click(); });
  await act(async () => emit({ kind: "correct", evidence: { sentPct: 20, reservePct: 80 } }));
  expect(host.querySelector(".quality-good")?.getAttribute("aria-label")).toBe("Good");
  await act(async () => { [...host.querySelectorAll("button")].find(b => b.textContent === "Back to Training")!.click(); });
  expect(api.report).toHaveBeenCalledWith({ kind: "passed", verdict: "Good" });
  await act(async () => root.unmount());
  const next = createRoot(host); await act(async () => next.render(<DrillOverlay ref={overlay} bridge={bridge} referee={referee} api={api} drill={drill} />));
  await act(async () => emit({ kind: "correct", evidence: { sentPct: 20, reservePct: 80 } }));
  expect(host.querySelector(".quality-great")?.textContent).toBe("! Great");
  await act(async () => overlay.current!.reset());
  await act(async () => emit({ kind: "correct", evidence: { sentPct: 20, reservePct: 80 } }));
  expect(host.querySelector(".quality-good")?.getAttribute("aria-label")).toBe("Good");
  await act(async () => next.unmount()); host.remove(); vi.unstubAllGlobals();
});
